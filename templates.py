def render_message(template: str, values: dict) -> str:
    """템플릿 내 변수 치환"""
    rendered = template
    for key, val in values.items():
        placeholder = f"{{{key}}}"
        rendered = rendered.replace(placeholder, str(val))
    return rendered


def calculate_korean_bytes(text: str) -> dict:
    """
    통신사 표준 문자 바이트 계산:
    - 한글/특수문자: 2바이트 (EUC-KR)
    - 영문/숫자/기본공백: 1바이트
    - 90바이트 이하: SMS (단문)
    - 91바이트 이상: LMS (장문, 최대 2,000바이트)
    """
    byte_count = 0
    for char in text:
        # EUC-KR 인코딩 시도, 불가능한 이모지는 UTF-8(4바이트 등) 또는 대체
        try:
            char_bytes = char.encode("euc-kr")
            byte_count += len(char_bytes)
        except UnicodeEncodeError:
            # 이모지 등 EUC-KR 미지원 문자는 보통 2바이트 이상으로 계산
            byte_count += 2

    is_lms = byte_count > 90
    msg_type = "LMS (장문)" if is_lms else "SMS (단문)"

    return {
        "bytes": byte_count,
        "max_bytes": 2000 if is_lms else 90,
        "type": msg_type,
        "is_lms": is_lms,
        "char_count": len(text),
    }
