"""
Place Insight Pro - 네이버 스마트플레이스 새소식 스튜디오
"""

from typing import Dict, Any

def generate_news_post(theme: str, store_info: Dict[str, Any]) -> Dict[str, Any]:
    """
    네이버 스마트플레이스 공식 규격 및 모바일 가독성에 최적화된 새소식 초안 생성
    """
    name = store_info.get("name", "저희 매장")
    region = store_info.get("region", "동네")
    category = store_info.get("category", "맛집")
    parking = store_info.get("parking", "편리한 주차 공간")
    
    if theme == "단체 모임":
        title = f"단체 모임·회식 예약, 이제 메뉴부터 편하게 준비하세요! 👥"
        body = f"""안녕하세요, {region} {category} 전문점 {name}입니다.

연말연시, 동호회, 가족 외식, 회사 회식 등 소중한 분들과의 단체 모임을 준비 중이신가요?

"몇 명까지 앉을 수 있을까?"
"주차는 넉넉할까?"
"어떤 메뉴로 시켜야 호불호 없이 만족할까?"

총무님과 모임 주최자분의 고민을 덜어드리고자, {name}에서는 단체 고객님들을 위해 이렇게 준비하고 있습니다:

1️⃣ 쾌적한 단체석 완비
테이블이 흩어지지 않고 한 공간에서 화기애애하게 대화 나누실 수 있도록 좌석을 사전 세팅해 드립니다.

2️⃣ 호불호 없는 알찬 모임 메뉴
어르신부터 아이까지 모두가 맛있게 즐길 수 있는 {name}의 대표 시그니처 메뉴들로 든든한 상차림을 약속드립니다.

3️⃣ 주차 걱정 없는 쾌적한 방문
{parking}으로 여러 대가 함께 오셔도 주차 스트레스 없이 편안하게 입장하실 수 있습니다.

📌 [단체 예약 꿀팁]
원하시는 시간대와 인원수를 네이버 예약 또는 전화로 미리 말씀해 주시면, 도착 즉시 식사하실 수 있도록 정갈하게 준비해 두겠습니다.

소중한 분들과 행복하고 맛있는 추억을 만드실 수 있도록 정성을 다해 모시겠습니다. 감사합니다! 😊"""
        photo_tip = "넓은 단체석 전경 사진 + 메인 메뉴가 풍성하게 차려진 항공샷 상차림 사진"
        tags = [f"#{region}회식", f"#{region}단체모임", f"#{region}{category}", f"#{name}", "#단체석완비", "#단체예약"]

    elif theme == "주차 및 찾아오는 길":
        title = f"주차 스트레스 NO! {name} 편하게 찾아오시는 길 안내 🚗"
        body = f"""안녕하세요, {name}입니다!

소중한 식사 시간에 가장 신경 쓰이는 것 중 하나가 바로 '주차와 찾아오는 길'이죠.
방문하시는 발걸음이 번거롭지 않도록 상세하게 안내해 드립니다.

📍 주소: {store_info.get('address', '매장 상세 주소')}
🚗 주차 안내: {parking}

네비게이션에 '{name}'을 검색하시고 오시면 전용 주차 공간으로 편리하게 진입하실 수 있습니다.

초행길이시거나 대중교통을 이용해 오시는 길에 헷갈리시는 점이 있다면 언제든 편하게 매장({store_info.get('tel', '전화')})으로 연락 주세요! 친절하게 안내해 드리겠습니다.

오늘도 안전 운전하시고, 따뜻하고 맛있는 한 끼 드시러 오세요! 든든하게 준비하고 기다리겠습니다. 🌿"""
        photo_tip = "매장 앞 쾌적한 전용 주차장 사진 + 매장 외관 간판 사진"
        tags = [f"#{region}맛집", f"#{name}", f"#{region}주차편한식당", "#주차가능", "#찾아오는길"]

    elif theme == "시그니처 메뉴":
        menu_items = store_info.get("menu_items", [])
        sig_menu = menu_items[0]["name"] if menu_items else "대표 메뉴"
        title = f"한 입 드셔보시면 압니다. {name}의 고집이 담긴 '{sig_menu}' 🍲"
        body = f"""안녕하세요! 정직한 맛을 이어가는 {name}입니다.

손님들이 저희 매장을 다시 찾아주시는 가장 큰 이유, 바로 시그니처 메뉴인 '{sig_menu}' 때문인데요.

왜 {name}의 {sig_menu}가 다를까요?

✨ 신선함이 곧 맛입니다
매일 새벽 엄선한 최상급 원재료만을 고집하며, 당일 손질·당일 조리를 철저히 지킵니다.

✨ 깊고 진한 정성의 시간
인공적인 조미료 맛이 아닌, 시간과 정성을 들여 우려낸 비법 육수와 정갈한 양념이 어우러져 한 그릇을 다 비우실 때까지 질리지 않는 깊은 맛을 냅니다.

오늘 소중한 분과 함께 든든하고 건강한 보양 한 끼 어떠세요?
항상 변함없는 감동의 맛으로 보답하겠습니다. 편하게 들러주세요! 👨‍🍳"""
        photo_tip = "시그니처 메뉴가 김이 모락모락 나는 생생한 근접 음식 사진"
        tags = [f"#{region}맛집", f"#{sig_menu}", f"#{name}", f"#{region}{category}", "#인생맛집", "#정직한한끼"]

    elif theme == "단골 쿠폰 이벤트":
        title = f"🎁 플레이스 저장하기 누르시면 '테이블당 음료/혜택' 쏩니다!"
        body = f"""안녕하세요, {name}을 아껴주시는 소중한 고객 여러분!

저희 매장을 믿고 찾아주시는 분들께 감사의 마음을 담아, 네이버 스마트플레이스 '저장하기' 특별 혜택을 준비했습니다!

📱 [참여 방법 - 단 10초!]
1. 네이버에서 '{name}'을 검색합니다.
2. 플레이스 상단의 [저장] (★ 별 모양) 버튼을 꾹 누릅니다.
3. 플레이스 [쿠폰] 메뉴에서 '웰컴 혜택 쿠폰'을 다운로드 받습니다.
4. 매장 방문 주문 시 직원에게 쿠폰 화면을 보여주시면 즉시 서비스 혜택을 드립니다!

식사하시는 모든 분들이 기분 좋게 머물다 가실 수 있도록 늘 작은 것 하나까지 정성을 다하겠습니다.
지금 바로 저장 누르시고 맛있는 혜택 챙겨가세요! 🥳"""
        photo_tip = "시원한 음료 서비스 사진 + 매장 홀의 밝고 친절한 분위기 사진"
        tags = [f"#{region}맛집", f"#{name}", "#플레이스이벤트", "#쿠폰이벤트", "#저장하기혜택", "#단골선물"]

    else: # 아이 놀이방/가족 편의
        title = f"엄마 아빠도 편안하게 식사하는 곳, {name} 가족석 & 놀이방 안내 👶"
        body = f"""아이들과 외식 한 번 하려면 "좌석은 편할까?", "아이 먹일 메뉴가 있을까?" 걱정부터 앞서시죠?

{region} {name}은 온 가족이 눈치 보지 않고 여유롭게 식사를 즐기실 수 있는 가족 친화 공간입니다.

🎈 우리 아이 안심 시설
- 청결하게 관리되는 유아의자(아기의자) 완비
- 아이들이 편하게 머물 수 있는 안전한 좌석 공간
- 자극적이지 않고 영양 가득한 어린이 안심 메뉴

엄마 아빠에게는 따뜻하고 여유로운 식사 시간을, 아이에게는 맛있는 즐거움을 선물해 드립니다.
가족 외식 고민하지 마시고 편안한 마음으로 찾아주세요! 👨‍👩‍👧‍👦"""
        photo_tip = "아이 놀이방/유아의자 비치 사진 + 아이와 가족이 밝게 식사하는 공간 사진"
        tags = [f"#{region}가족외식", f"#{region}놀이방식당", f"#{region}아이동반", f"#{name}", "#키즈존", "#가족모임"]

    return {
        "theme": theme,
        "title": title,
        "body": body,
        "photo_tip": photo_tip,
        "tags": tags
    }
